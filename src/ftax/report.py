from __future__ import annotations

import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from . import analysis as A  # noqa: E402
from . import config as C  # noqa: E402
from .prompts import CONDITIONS, DRIFT_LABEL, DRIFT_VARIANTS, LABEL  # noqa: E402

COLORS = {"qwen3:8b": "#5b4fc9", "llama3.1:8b": "#d1773a", "gemma3:12b": "#2f8f6f", "qwen3:30b-a3b": "#8a8a8a"}
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.titleweight": "bold", "savefig.dpi": 200, "savefig.bbox": "tight"})


def pct(x, digits=1) -> str:
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{digits}f}%"


def pp(x, digits=1) -> str:
    return "–" if x is None or np.isnan(x) else f"{100 * x:+.{digits}f}"


def ci(lo, hi, digits=1) -> str:
    return f"[{100 * lo:+.{digits}f}, {100 * hi:+.{digits}f}]"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


# ---------------------------------------------------------------- figures

def fig_accuracy(acc: pd.DataFrame, path: str):
    tasks = ["gsm8k", "mmlu"]
    models = [m for m in C.MODELS if m in set(acc.model)]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.6), sharey=True)
    ys = np.arange(len(CONDITIONS))[::-1]
    for ax, task in zip(axes, tasks):
        for k, m in enumerate(models):
            g = acc[(acc.model == m) & (acc.task == task)].set_index("condition")
            off = (k - (len(models) - 1) / 2) * 0.18
            for y, c in zip(ys, CONDITIONS):
                if c not in g.index:
                    continue
                r = g.loc[c]
                ax.plot([r.lo, r.hi], [y + off] * 2, color=COLORS[m], lw=1.4, alpha=0.7)
                ax.plot(r.acc, y + off, "o", color=COLORS[m], ms=5, label=m if y == ys[0] else None)
        ax.set_title({"gsm8k": "GSM8K (maths)", "mmlu": "MMLU (multiple choice)"}[task])
        ax.set_xlim(0, 1)
        ax.xaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1))
        ax.set_xlabel("accuracy")
        ax.grid(axis="x", alpha=0.25)
    axes[0].set_yticks(ys, [LABEL[c] for c in CONDITIONS])
    axes[1].legend(loc="lower left", frameon=False, fontsize=9)
    fig.suptitle("Accuracy by output format, with 95% intervals", x=0.02, ha="left")
    fig.savefig(path)
    plt.close(fig)


def fig_drift(dc: pd.DataFrame, path: str):
    models = [m for m in C.MODELS if m in set(dc.model)]
    vs = [v for v in DRIFT_VARIANTS if v != "base"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.4), sharey=True)
    ys = np.arange(len(vs))[::-1]
    for ax, mode in zip(axes, ["json", "schema"]):
        for k, m in enumerate(models):
            g = dc[(dc.model == m) & (dc["mode"] == mode)].set_index("variant")
            off = (k - (len(models) - 1) / 2) * 0.2
            for y, v in zip(ys, vs):
                if v not in g.index:
                    continue
                r = g.loc[v]
                ax.plot([r.lo, r.hi], [y + off] * 2, color=COLORS[m], lw=1.4, alpha=0.7)
                ax.plot(r["diff"], y + off, "o", color=COLORS[m], ms=5, label=m if y == ys[0] else None)
        ax.axvline(0, color="#999", lw=0.8)
        ax.set_title({"json": "JSON asked for in the prompt", "schema": "Schema-constrained decoding"}[mode])
        ax.xaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1, decimals=1))
        ax.set_xlabel("change in field accuracy vs the base export (pp)")
        ax.grid(axis="x", alpha=0.25)
    axes[0].set_yticks(ys, [DRIFT_LABEL[v] for v in vs])
    axes[0].legend(loc="lower left", frameon=False, fontsize=9)
    fig.suptitle("Extraction accuracy when the source format drifts, with 95% intervals", x=0.02, ha="left")
    fig.savefig(path)
    plt.close(fig)


