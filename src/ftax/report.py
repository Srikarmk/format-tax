def write_report(split: str = "main"):
    df = A.load(split)
    os.makedirs(C.FIGURES, exist_ok=True)
    out = [f"# Results ({split} items)", "",
           "Generated by `ftax report` from `results/answers/`. Intervals are 95% item bootstraps (2,000 draws).", ""]
    a, b = A.part_a(df), A.part_b(df)

    if len(a):
        acc = A.accuracy_table(a)
        fig_accuracy(acc, os.path.join(C.FIGURES, "accuracy.png"))
        out += ["## Part A: accuracy by output format", "", "![accuracy](figures/accuracy.png)", ""]
        for task in ["gsm8k", "mmlu"]:
            t = acc[acc.task == task]
            if not len(t):
                continue
            rows = []
            for c in A.CONDITIONS + list(A.AA):
                cells = [LABEL[c]]
                for m in A.models_in(t):
                    r = t[(t.model == m) & (t.condition == c)]
                    cells.append("–" if not len(r) else
                                 f"{pct(r.acc.iloc[0], 0)} (n={r.n.iloc[0]}, {r.tokens.iloc[0]:.0f} tok)")
                rows.append(cells)
            out += [f"### {task}", "", md_table(pd.DataFrame(rows, columns=["condition"] + A.models_in(t))), ""]

        con = A.contrast_table(a)
        out += ["## Part A: contrasts (pp, paired by item)", ""]
        rows = []
        for r in con.itertuples():
            rows.append([r.task, r.model, r.contrast, pp(r.diff), ci(r.lo, r.hi), r.n])
        out += [md_table(pd.DataFrame(rows, columns=["task", "model", "contrast", "diff", "95% CI", "n"])), ""]

        val = acc[acc.condition.str.startswith(("json_", "schema_"))]
        rows = [[r.task, r.model, LABEL[r.condition], pct(r.acc, 0), pct(r.written, 0), pct(r.json_found, 0),
                 pct(r.json_strict, 0), r.rescued, r.truncated] for r in val.itertuples()]
        out += ["## Part A: JSON validity", "",
                "`accuracy` counts a reply with no valid JSON answer as wrong; `as written` scores the value written after "
                '`"answer":` even when the JSON never closed. `found` = a JSON object with a usable answer anywhere in the '
                "reply; `strict` = the whole reply is that object; `rescued` = invalid replies a free-text parser would "
                "have scored right.", "",
                md_table(pd.DataFrame(rows, columns=["task", "model", "condition", "accuracy", "as written", "found",
                                                     "strict", "rescued", "truncated"])), ""]

        sc = A.self_contradiction(a)
        if len(sc):
            rows = [[r.model, LABEL[r.condition], r.with_both, r.differ, pct(r.differ_rate), r.later_right,
                     r.answer_right_when_differ] for r in sc.itertuples()]
            out += ["## Part A: answer first, then reasoning (GSM8K)", "",
                    "How often the reasoning written after the answer ends on a different number.", "",
                    md_table(pd.DataFrame(rows, columns=["model", "condition", "replies with both", "differ",
                                                         "rate", "later number right", "answer right"])), ""]

        aa = A.aa_table(a)
        rows = [[r.task, r.model, LABEL[r.condition], f"{r.flips}/{r.n}", pct(r.rate)] for r in aa.itertuples()]
        out += ["## Part A: noise floor (A/A)", "",
                md_table(pd.DataFrame(rows, columns=["task", "model", "condition", "answers changed", "rate"])), ""]

    if len(b):
        dt, dc = A.drift_table(b), A.drift_contrasts(b)
        fig_drift(dc[dc["mode"].isin(["json", "schema"])], os.path.join(C.FIGURES, "drift.png"))
        out += ["## Part B: field accuracy by source format", "", "![drift](figures/drift.png)", ""]
        rows = []
        for v in DRIFT_VARIANTS:
            cells = [DRIFT_LABEL[v]]
            for m in A.models_in(b):
                for mode in ["json", "schema"]:
                    r = dt[(dt.model == m) & (dt.variant == v) & (dt["mode"] == mode)]
                    cells.append("–" if not len(r) else f"{pct(r.field_acc.iloc[0])} / {pct(r.exact.iloc[0], 0)}")
            rows.append(cells)
        cols = ["source format"] + [f"{m} {mode}" for m in A.models_in(b) for mode in ["json", "schema"]]
        out += ["Field accuracy / whole-record exact match.", "", md_table(pd.DataFrame(rows, columns=cols)), ""]

        rows = [[r["model"], r["mode"], DRIFT_LABEL[r["variant"]], pp(r["diff"]), ci(r["lo"], r["hi"])] for _, r in dc.iterrows()]
        out += ["## Part B: contrasts (pp of field accuracy, paired by record)", "",
                md_table(pd.DataFrame(rows, columns=["model", "mode", "source format", "diff", "95% CI"])), ""]

        rf = A.reformat_table(b)
        rows = [[r.model, r.mode, r.field, r.n, pct(r.reformatted), pct(r.base), pp(r.diff), ci(r.lo, r.hi)]
                for r in rf.itertuples()]
        out += ["## Part B: reformatted values, on the changed fields only", "",
                md_table(pd.DataFrame(rows, columns=["model", "mode", "field", "n", "reformatted", "base", "diff", "95% CI"])), ""]

        dr = A.dropped_table(b)
        rows = [[r.model, r.mode, pct(r.dropped_filled), ci(r.lo, r.hi).replace("+", ""), pct(r.natural_filled),
                 r.n_natural] for r in dr.itertuples()]
        out += ["## Part B: a missing field filled in", "",
                "Share of records where the model gave a value for the removed field, against fields the base record never had.", "",
                md_table(pd.DataFrame(rows, columns=["model", "mode", "removed field filled", "95% CI",
                                                     "never-present field filled", "n never-present"])), ""]

        ds = A.distractor_table(b)
        rows = [[r.model, r.mode, f"{r.took}/{r.n}", pct(r.rate)] for r in ds.itertuples()]
        out += ["## Part B: look-alike fields taken", "",
                md_table(pd.DataFrame(rows, columns=["model", "mode", "records", "rate"])), ""]

        rows = [[r.model, r.mode, pct(r.parsed, 0), pct(r.json_strict, 0), pct(r.keys_exact, 0)]
                for r in dt.groupby(["model", "mode"])[["parsed", "json_strict", "keys_exact"]].mean().reset_index().itertuples()]
        out += ["## Part B: validity", "",
                md_table(pd.DataFrame(rows, columns=["model", "mode", "parsed", "strict", "exact keys"])), ""]

        aa = A.drift_aa(b)
        rows = [[r.model, r.mode, f"{r.flips}/{r.n}"] for r in aa.itertuples()]
        out += ["## Part B: noise floor (A/A)", "", md_table(pd.DataFrame(rows, columns=["model", "mode", "answers changed"])), ""]

    name = "results.md" if split == "main" else f"results_{split}.md"
    with open(os.path.join(C.REPORTS, name), "w") as f:
        f.write("\n".join(out))
    print(f"wrote reports/{name}")
